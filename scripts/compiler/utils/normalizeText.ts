export function normalizeText(text: string) {
  return text

    // -----------------------------
    // Bullets
    // -----------------------------
    .replace(/â€¢/g, "•")
    .replace(/Γ£à/g, "•")

    // -----------------------------
    // Arrows
    // -----------------------------
    .replace(/â†’/g, "→")
    .replace(/â†“/g, "↓")
    .replace(/â†�/g, "←")
    .replace(/ΓåÆ/g, "→")

    // -----------------------------
    // Dashes
    // -----------------------------
    .replace(/ΓÇö/g, "—")
    .replace(/â€”/g, "—")
    .replace(/ΓÇô/g, "–")
    .replace(/â€“/g, "–")

    // -----------------------------
    // Quotes
    // -----------------------------
    .replace(/â€œ/g, "“")
    .replace(/â€/g, "”")
    .replace(/â€˜/g, "‘")
    .replace(/â€™/g, "’")

    // -----------------------------
    // Ellipsis
    // -----------------------------
    .replace(/â€¦/g, "…")

    // -----------------------------
    // Box drawing
    // -----------------------------
    .replace(/â”œ/g, "├")
    .replace(/â”€/g, "─")
    .replace(/â””/g, "└")
    .replace(/â”‚/g, "│")
    .replace(/â–¼/g, "▼")

    .replace(/Γö£ΓöÇΓöÇ/g, "├──")
    .replace(/ΓööΓöÇΓöÇ/g, "└──")

    // -----------------------------
    // Checkboxes
    // -----------------------------
    .replace(/Γ¼£/g, "□")
    .replace(/Γ£î/g, "☑")

    // -----------------------------
    // Misc icons
    // -----------------------------
    .replace(/≡ƒÅ¢∩╕Å/g, "💡")
    .replace(/∩╕Å/g, "")
    .replace(/ƒÅ¢/g, "💡")

    // -----------------------------
    // Cleanup
    // -----------------------------
    .replace(/Â/g, "")
    .replace(/\u00A0/g, " ")
    .replace(/[ \t]{2,}/g, " ")
    .trim();
}